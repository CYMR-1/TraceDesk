class GuideDialog(QDialog):
    def __init__(self, parent):
        super().__init__(parent)
        self.setWindowTitle('操作说明 · TraceDesk')
        self.resize(720, 500)
        layout = QVBoxLayout(self)
        navigation = QHBoxLayout()
        topics = QComboBox()
        topics.addItems([title for title, _ in GUIDE_PAGES])
        label = QLabel('操作主题')
        label.setBuddy(topics)
        navigation.addWidget(label)
        navigation.addWidget(topics, 1)
        layout.addLayout(navigation)
        body = QTextBrowser()
        layout.addWidget(body)
        controls = QHBoxLayout()
        position = QLabel()
        controls.addWidget(position)
        controls.addStretch()
        back = QPushButton('上一步')
        forward = QPushButton('下一步')
        close = QPushButton('关闭')
        for button in (back, forward, close):
            controls.addWidget(button)
        layout.addLayout(controls)

        def show_step(index):
            body.setMarkdown(GUIDE_PAGES[index][1])
            body.verticalScrollBar().setValue(0)
            position.setText(f'第 {index + 1} / {len(GUIDE_PAGES)} 页')
            back.setEnabled(index > 0)
            forward.setEnabled(index + 1 < len(GUIDE_PAGES))

        topics.currentIndexChanged.connect(show_step)
        back.clicked.connect(lambda: topics.setCurrentIndex(topics.currentIndex() - 1))
        forward.clicked.connect(lambda: topics.setCurrentIndex(topics.currentIndex() + 1))
        close.clicked.connect(self.accept)
        show_step(0)


def show_guide(context):
    dialog = GuideDialog(context.root)
    try:
        dialog.exec()
    finally:
        dialog.deleteLater()


FEATURE = Feature('help', actions=(Action('help', show_guide, '操作说明', 'brand', 'pager'),))
